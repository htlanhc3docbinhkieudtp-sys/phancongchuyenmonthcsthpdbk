// Backwards compatibility alias
const TEACHER_MAP = THCS_DBK_TEACHER_MAP;

// Helper to normalize teacher code / name
export function getTHCSDBKTeacherInfo(rawTeacher: string): { id: string; name: string; code: string } {
  const trimmed = rawTeacher.trim();
  if (TEACHER_MAP[trimmed]) return TEACHER_MAP[trimmed];
  const stripped = trimmed.replace(/^HN-/, '').trim();
  if (TEACHER_MAP[stripped]) return TEACHER_MAP[stripped];
  return { id: '', name: trimmed, code: trimmed };
}

// Helper to normalize subject
export function getTHCSDBKSubjectInfo(rawSubject: string): { id: string; name: string } {
  const s = rawSubject.trim();
  if (s.startsWith('Chào cờ')) return { id: 'sub-chao-co', name: 'Chào cờ' };
  if (s.startsWith('HĐ TN-HN(CĐ)') || s.startsWith('HĐTN-HN(CĐ)') || s.startsWith('HĐ TN-HN (CĐ)') || s.includes('Chuyên đề') || s.includes('theo chủ đề') || s.includes('HĐ CĐ') || s.includes('HD CD')) {
    return { id: 'sub-hdtn-cd', name: 'HĐTNHN (Chuyên đề)' };
  }
  if (s === 'SHL' || s.startsWith('SHL-') || s.startsWith('SHL -') || s === 'Sinh hoạt lớp' || s.startsWith('Sinh hoạt lớp')) {
    return { id: 'sub-shl', name: 'Sinh hoạt lớp' };
  }
  if (s.startsWith('HĐ TN-HN(SHL)') || s.startsWith('HĐTN-HN(SHL)') || s.startsWith('HĐCN') || s.startsWith('HĐ Chủ nhiệm') || s.includes('QML') || s.includes('quy mô lớp') || s.includes('chủ nhiệm')) {
    return { id: 'sub-hdtn-cd', name: 'HĐTNHN (Quy mô lớp)' };
  }
  if (s.startsWith('HĐ TN-HN') || s.startsWith('HĐTN-HN') || s.startsWith('HĐ TN') || s.startsWith('HĐTN')) {
    return { id: 'sub-hdtn-cd', name: 'HĐTNHN (Chuyên đề)' };
  }
  if (s === 'Toán') return { id: 'sub-toan', name: 'Toán học' };
  if (s === 'Ngữ văn') return { id: 'sub-van', name: 'Ngữ văn' };
  if (s === 'Ngoại ngữ') return { id: 'sub-anh', name: 'Tiếng Anh' };
  if (s === 'KHTN') return { id: 'sub-khtn-cs', name: 'Khoa học tự nhiên' };
  if (s === 'Vật lí' || s === 'Vật lý') return { id: 'sub-li', name: 'Vật lí' };
  if (s === 'Hóa học') return { id: 'sub-hoa', name: 'Hóa học' };
  if (s === 'Sinh học') return { id: 'sub-sinh', name: 'Sinh học' };
  if (s === 'Lịch sử và Địa lý' || s === 'Lịch sử và Địa lí') return { id: 'sub-lsdl-cs', name: 'Lịch sử và Địa lí' };
  if (s === 'Lịch Sử' || s === 'Lịch sử') return { id: 'sub-su', name: 'Lịch sử' };
  if (s === 'Địa Lí' || s === 'Địa lí') return { id: 'sub-dia', name: 'Địa lí' };
  if (s === 'GDCD') return { id: 'sub-gdcd', name: 'Giáo dục công dân' };
  if (s === 'Tin học') return { id: 'sub-tin', name: 'Tin học' };
  if (s === 'Công nghệ') return { id: 'sub-cn', name: 'Công nghệ' };
  if (s === 'GDTC') return { id: 'sub-gdtc', name: 'Giáo dục thể chất' };
  if (s === 'Âm nhạc') return { id: 'sub-am-nhac', name: 'Âm nhạc' };
  if (s === 'Mỹ thuật') return { id: 'sub-my-thuat', name: 'Mỹ thuật' };
  return { id: 'sub-khac', name: s };
}

// Build helper for a class schedule
function buildClassSchedule(
  classId: string,
  className: string,
  session: 'SANG' | 'CHIEU',
  rawSchedule: { day: number; period: number; text: string }[]
): TimetableSlot[] {
  return rawSchedule.map(item => {
    // text format: "Môn-TênGV" e.g., "KHTN-Tài" or "Chào cờ-Tài" or "HĐ TN-HN(CĐ)-Thị Hậu"
    let subjectPart = item.text;
    let teacherPart = '';

    const lastDashIdx = item.text.lastIndexOf('-');
    if (lastDashIdx !== -1) {
      subjectPart = item.text.substring(0, lastDashIdx).trim();
      teacherPart = item.text.substring(lastDashIdx + 1).trim();
    }

    const subInfo = getTHCSDBKSubjectInfo(subjectPart);
    const tchInfo = getTHCSDBKTeacherInfo(teacherPart);

    const isSpecial = subjectPart.startsWith('Chào cờ') || subjectPart.startsWith('SHL') || subjectPart.startsWith('HĐCN') || subjectPart.includes('SHL');

    return {
      id: `${classId}_w1_${item.day}_${session}_${item.period}`,
      classId,
      className,
      dayOfWeek: item.day,
      session,
      period: item.period,
      subjectId: subInfo.id,
      subjectName: subInfo.name,
      teacherId: tchInfo.id,
      teacherName: tchInfo.name,
      teacherCode: tchInfo.code,
      room: '',
      isSpecialActivity: isSpecial
    };
  });
}

